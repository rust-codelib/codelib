//! Арифметический контракт статического элемента конечного поля.

use core::fmt::Debug;
use core::ops::{Add, Mul, Neg, Sub};

/// Операции, необходимые линейной алгебре над одним статическим полем.
///
/// Реализация должна соблюдать законы поля: нуль и единица различны,
/// `a + 0 == a`, `a * 1 == a`, `a - a == 0`, сложение и умножение
/// ассоциативны и коммутативны, умножение дистрибутивно относительно
/// сложения, а `-a` является противоположным элементом. Для ненулевого `a`
/// `a * a.inv() == 1`. Компилятор проверяет сигнатуры и наличие операторов,
/// но не доказывает эти математические законы.
///
/// Каждый реализующий тип представляет одно фиксированное поле. Его значения
/// уже должны быть допустимыми элементами этого поля. Параметры поля
/// проверяются крейтом поля и вызывающим кодом; этот трейт их не проверяет.
/// Для многочленного модуля вызывающий код должен выбрать неприводимый модуль,
/// чтобы операции действительно задавали поле.
///
/// Трейт предназначен для статических полей: `zero` и `one` не требуют
/// параметров времени выполнения. Метод `inv` вызывается только для ненулевого
/// элемента алгоритмами `gf-linalg`; его поведение для нуля не используется.
///
/// `Copy` позволяет брать небольшие элементы для вычислений без отдельного
/// контракта владения, `Eq` нужен для сравнений, а `Debug` — для диагностики.
/// Текстовое представление намеренно не входит в арифметический интерфейс.
pub trait FieldElement:
    Copy
    + Eq
    + Debug
    + Add<Output = Self>
    + Sub<Output = Self>
    + Mul<Output = Self>
    + Neg<Output = Self>
{
    /// Возвращает нулевой элемент поля.
    fn zero() -> Self;

    /// Возвращает единичный элемент поля.
    fn one() -> Self;

    /// Возвращает мультипликативный обратный элемент.
    ///
    /// Линейные алгоритмы `gf-linalg` вызывают этот метод только для ненулевого
    /// значения. Поведение для нуля определяется конкретным типом поля.
    fn inv(self) -> Self;

    /// Возвращает `true`, если значение является нулём поля.
    fn is_zero(self) -> bool {
        self == Self::zero()
    }
}

impl<const N: usize, const POLY: u32> FieldElement for gf2m::Gf<N, POLY> {
    fn zero() -> Self {
        gf2m::Gf::<N, POLY>::zero()
    }

    fn one() -> Self {
        gf2m::Gf::<N, POLY>::one()
    }

    fn inv(self) -> Self {
        gf2m::Gf::<N, POLY>::inv(self)
    }
}

impl<const P: u32, const M: usize, const POLY: u128> FieldElement for gfpm::Gf<P, M, POLY> {
    fn zero() -> Self {
        gfpm::Gf::<P, M, POLY>::zero()
    }

    fn one() -> Self {
        gfpm::Gf::<P, M, POLY>::one()
    }

    fn inv(self) -> Self {
        gfpm::Gf::<P, M, POLY>::inv(self)
    }
}
