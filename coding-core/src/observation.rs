//! Наблюдение за событиями и соглашения о знаке мягких оценок.

/// Синхронно получает события в порядке, определённом кодеком.
///
/// Наблюдение не должно менять математический результат и не позволяет отменить
/// операцию. Кодек документирует порядок событий, в том числе при ошибках.
/// Обработчик должен завершаться нормально: восстановление после его паники
/// не гарантируется.
pub trait Observer<Event: ?Sized> {
    /// Обрабатывает событие; ссылка на него действительна только на время вызова.
    fn on_event(&mut self, event: &Event);
}

impl<Event: ?Sized, F: FnMut(&Event)> Observer<Event> for F {
    fn on_event(&mut self, event: &Event) {
        self(event);
    }
}

/// Игнорирует события без выделения памяти.
#[derive(Clone, Copy, Debug, Default)]
pub struct NoopObserver;

impl<Event: ?Sized> Observer<Event> for NoopObserver {
    fn on_event(&mut self, _: &Event) {}
}

/// Соглашение о знаке логарифмического отношения правдоподобий (LLR).
///
/// Используется натуральный логарифм. Тип входа конкретного декодера отдельно
/// определяет порядок позиций, насыщение, стирания, выбор бита при нуле
/// и допустимость `NaN` и бесконечностей.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum LlrConvention {
    /// `ln(P(bit = 0) / P(bit = 1))`: положительное значение в пользу нуля.
    PositiveForZero,
    /// `ln(P(bit = 1) / P(bit = 0))`: положительное значение в пользу единицы.
    PositiveForOne,
}

impl LlrConvention {
    /// Переводит значение из текущего соглашения о знаке в `target`.
    ///
    /// При смене соглашения меняет знак, включая знак нуля и бесконечности;
    /// `NaN` остаётся `NaN`. Метод не проверяет допустимость значения и не
    /// выполняет насыщение. Эти проверки и обработку стираний выполняет кодек.
    #[must_use]
    pub fn convert(self, value: f64, target: Self) -> f64 {
        if self == target {
            value
        } else {
            -value
        }
    }
}
