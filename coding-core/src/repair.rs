//! Ремонт: выбор помощников, вычисление ответов и восстановление потерянных данных.

use crate::Observer;

/// Результат поиска плана ремонта по доступным помощникам.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum RepairPlan<Plan, Unavailable> {
    /// План с контекстом, целью ремонта и запросами к помощникам.
    Ready(Plan),
    /// С данным набором помощников план не найден; это не ошибка входа.
    Unavailable(Unavailable),
}

/// Выбирает помощников и составляет запросы для восстановления цели.
///
/// План и запросы должны связывать полный контекст кода и блока, цель ремонта
/// и идентификаторы помощников. Поддержка ремонта задаётся отдельным трейтом:
/// ```compile_fail
/// use coding_core::RepairPlanner;
/// struct BlockOnly;
/// fn needs_repair<P: RepairPlanner<()>>(_: P) {}
/// needs_repair(BlockOnly);
/// ```
pub trait RepairPlanner<Request> {
    /// План, из которого можно получить запрос каждому помощнику.
    type Plan;
    /// Причина отсутствия плана при данном наборе помощников.
    type Unavailable;
    /// Ошибка запроса, контекста или ресурсов.
    type Error;
    /// Событие планирования ремонта.
    type Event;

    /// Составляет план без чтения данных помощников и полного декодирования.
    fn plan(
        &self,
        request: Request,
        observer: &mut dyn Observer<Self::Event>,
    ) -> Result<RepairPlan<Self::Plan, Self::Unavailable>, Self::Error>;
}

/// Вычисляет ответ помощника по запросу для конкретной цели ремонта.
///
/// Ответом может быть целый символ или вычисленный фрагмент данных узла.
/// Ответ должен содержать достаточно сведений о контексте, цели и помощнике,
/// чтобы восстановитель мог проверить его соответствие запросу.
pub trait RepairHelper<Request> {
    /// Вычисленный ответ, связанный с целью ремонта.
    type Response;
    /// Недоступность помощника, ошибка запроса, контекста или ресурсов.
    type Error;
    /// Событие обработки запроса помощником.
    type Event;

    /// Проверяет запрос и вычисляет ответ по данным этого помощника.
    fn respond(
        &self,
        request: Request,
        observer: &mut dyn Observer<Self::Event>,
    ) -> Result<Self::Response, Self::Error>;
}

/// Восстанавливает цель по плану и ответам помощников.
///
/// `Input` может содержать срез ответов или функцию их чтения, выходной
/// и рабочий буферы. Перед возвратом результата реализация проверяет контекст
/// плана, цель, ID помощника и форму каждого ответа, достаточность данных,
/// отсутствие пропущенных и повторных ответов.
///
/// Чтение хранилища и транспорт предоставляет вызывающий код. Метрики операции
/// должны учитывать только фактически наблюдаемые обращения и объёмы данных.
pub trait RepairExecutor<Input> {
    /// Восстановленная цель: отдельная часть или узел, не обязательно всё сообщение.
    type Output;
    /// Неполные или неверные ответы, ошибка контекста, формы или ресурсов.
    type Error;
    /// Событие восстановления цели.
    type Event;

    /// Выполняет ремонт без доступа к потерянной цели или исходному сообщению.
    fn repair(
        &self,
        input: Input,
        observer: &mut dyn Observer<Self::Event>,
    ) -> Result<Self::Output, Self::Error>;
}
