//! Кодирование, декодирование и обработка частей подготовленного блока.

use crate::{DecodeOutcome, Observer};

/// Кодирует сообщение или подготавливает сессию одного блока.
///
/// `Input` может содержать входные срезы, выходной и рабочий буферы вызывающего
/// кода. Реализация проверяет настройки, размеры, значения и длину сообщения
/// в передаваемом представлении: не более [`crate::MAX_MESSAGE_BYTES`] байт.
///
/// Реализация документирует изменения переданных буферов и своего состояния,
/// в том числе при ошибке. Общий трейт не задаёт алфавит и длину выхода.
pub trait Encoder<Input> {
    /// Кодовый блок или подготовленная сессия с реализацией [`SymbolEncoder`].
    type Output;
    /// Ошибка входных данных, контекста, размера или ресурсов конкретного кодера.
    type Error;
    /// Событие кодера; `()`, если событий нет.
    type Event;

    /// Выполняет кодирование и передаёт события наблюдателю.
    ///
    /// Для вызова без обработки событий передают [`crate::NoopObserver`].
    fn encode(
        &mut self,
        input: Input,
        observer: &mut dyn Observer<Self::Event>,
    ) -> Result<Self::Output, Self::Error>;
}

/// Выполняет попытку декодирования переданных наблюдений канала.
///
/// Реализация определяет контекст блока, порядок позиций, смысл результата,
/// доступные проверки, причины остановки и изменения своего состояния.
/// [`DecodeOutcome::NeedMore`] означает нехватку данных, а не ошибку входа.
///
/// Реализация проверяет контекст, форму и значения входа, а также размер
/// исходного и восстановленного сообщения: не более [`crate::MAX_MESSAGE_BYTES`]
/// байт передаваемого представления. Для выходного и рабочего буферов вызывающего
/// кода документируются изменения при успехе и при ошибке.
///
/// Декодер может обрабатывать каждый набор наблюдений независимо, без их
/// сохранения между вызовами. Накопление данных описывает [`IncrementalDecoder`].
/// Одному кодеру могут соответствовать несколько разных декодеров.
///
/// Несовместимый тип входа отклоняется при компиляции:
/// ```compile_fail
/// use coding_core::{Decoder, NoopObserver};
/// fn wrong<D: for<'a> Decoder<&'a [u8]>>(decoder: &mut D) {
///     let _ = decoder.decode("not observations", &mut NoopObserver);
/// }
/// ```
pub trait Decoder<Input> {
    /// Тип кандидата с указанным смыслом данных, например [`crate::Codeword`].
    type Value;
    /// Результаты проверок кандидата; не гарантируют совпадение с оригиналом.
    type Checks;
    /// Причина ожидания дополнительных данных; может содержать прогресс.
    type NeedMore;
    /// Причина завершения попытки без кандидата.
    type StopReason;
    /// Ошибка данных, контекста, вычислений или ресурсов.
    ///
    /// Реализация документирует влияние каждой ошибки на своё состояние.
    type Error;
    /// Событие декодера для наблюдения за ходом операции.
    type Event;

    /// Возвращает исход попытки декодирования либо ошибку.
    ///
    /// Трейт не требует копирования входа или выделения памяти.
    #[allow(clippy::type_complexity)]
    fn decode(
        &mut self,
        input: Input,
        observer: &mut dyn Observer<Self::Event>,
    ) -> Result<
        DecodeOutcome<Self::Value, Self::Checks, Self::NeedMore, Self::StopReason>,
        Self::Error,
    >;
}

/// Генерирует часть подготовленного блока по её идентификатору.
///
/// Один контекст и один ID всегда дают одинаковую часть. Реализация проверяет
/// допустимость ID; результат не зависит от скрытого счётчика вызовов.
/// Для нового блока создают отдельную сессию с его контекстом.
pub trait SymbolEncoder<Id> {
    /// Сгенерированная часть с контекстом блока, если он необходим для обработки.
    type Symbol;
    /// Ошибка идентификатора, размера или ресурсов.
    type Error;
    /// Событие генерации части.
    type Event;

    /// Генерирует одну часть без обязательного создания остальных частей.
    fn symbol(
        &self,
        id: Id,
        observer: &mut dyn Observer<Self::Event>,
    ) -> Result<Self::Symbol, Self::Error>;
}

/// Накапливает наблюдения одного блока с заранее заданным контекстом.
///
/// Реализация задаёт собственные типы `Progress` и `Update`: ранг и число
/// пакетов имеют смысл не для каждого алгоритма. Она документирует обработку
/// повторов и противоречий, приём после завершения, ограничения ресурсов
/// и ошибки, после которых накопленные данные больше нельзя использовать.
///
/// Реализовывать [`Decoder`] или общий метод сброса состояния не требуется.
pub trait IncrementalDecoder<Input> {
    /// Текущее состояние: прогресс, завершение или непригодность накопленных данных.
    type Progress;
    /// Результат обработки очередного входа и его диагностика.
    type Update;
    /// Кандидат и результаты его проверок, доступные по ссылке.
    type Output: ?Sized;
    /// Ошибка входа, ресурсов или противоречие, делающее накопленные данные непригодными.
    type Error;
    /// Событие приёма и обработки данных.
    type Event;

    /// Принимает наблюдение, проверив полный контекст перед его использованием.
    fn push(
        &mut self,
        input: Input,
        observer: &mut dyn Observer<Self::Event>,
    ) -> Result<Self::Update, Self::Error>;

    /// Возвращает прогресс без изменения состояния.
    fn progress(&self) -> Self::Progress;

    /// Возвращает ссылку на текущего кандидата.
    ///
    /// Если накопленные данные признаны непригодными, возвращает `None`.
    /// Изменять декодер можно после завершения заимствования результата.
    /// Ранее сделанные вызывающим кодом копии результата отозвать невозможно.
    fn result(&self) -> Option<&Self::Output>;
}
