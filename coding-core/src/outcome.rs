//! Кандидат декодирования, результаты его проверок и исход попытки.

/// Сообщение в порядке и представлении, определённых кодеком.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Message<T>(pub T);

/// Кодовое слово в передаваемом представлении.
///
/// Сообщение не обязательно располагается в первых позициях слова.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Codeword<T>(pub T);

/// Входной вектор преобразования, например полярного кодера.
///
/// Отличается по смыслу от передаваемого кодового слова.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct TransformInput<T>(pub T);

/// Предполагаемый результат и фактически выполненные кодеком проверки.
///
/// `Checks` описывает, что проверено, какие проверки прошли и какие не выполнялись.
/// Успешная проверка чётности, контрольной суммы или согласованности не доказывает
/// совпадение с отправленным оригиналом. Это сравнение выполняет отдельно
/// тестовый стенд с известным оригиналом.
///
/// Собственный тип результата кодека может дополнительно хранить мягкие оценки
/// и диагностику остановки алгоритма.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Candidate<Value, Checks> {
    /// Сообщение, кодовое слово, вход преобразования или иной документированный результат.
    pub value: Value,
    /// Результаты проверок; не означают гарантированного совпадения с оригиналом.
    pub checks: Checks,
}

/// Исход попытки декодирования.
///
/// Ошибки входных данных и ресурсов возвращаются отдельно через `Result::Err`.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum DecodeOutcome<Value, Checks, NeedMore, StopReason> {
    /// Получен кандидат; его проверки могут быть неуспешными или невыполненными.
    Candidate(Candidate<Value, Checks>),
    /// Нужны дополнительные наблюдения; сохранение текущего входа не гарантируется.
    NeedMore(NeedMore),
    /// Попытка завершена без кандидата, например из-за исчерпания числа итераций.
    Stopped(StopReason),
}
