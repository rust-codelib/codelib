#![forbid(unsafe_code)]
#![warn(missing_docs)]

//! gfpm — конечные поля GF(p^m) для произвольного простого p.
//!
//! Ограничение одно: **порядок поля `p^m <= 2^64`** (коэффициенты
//! живут в `u32`, то есть `p < 2^32`). Простые поля GF(p) — частный
//! случай `m = 1`; характеристика 2 тоже поддерживается — для неё
//! есть и отдельный оптимизированный крейт [`gf2m`] этого же
//! воркспейса (таблицы, clmul), с которым gfpm сверяется тестами.
//!
//! Четыре слоя:
//! - [`fp`] — арифметика простого поля GF(p): константные
//!   модулярные примитивы, проверка простоты;
//! - [`poly`] — многочлены над GF(p): умножение, деление, НОД,
//!   тест Рабина на неприводимость, поиск неприводимых, упаковка
//!   коэффициентов в базисе p;
//! - [`Gf<P, M, POLY>`](Gf) — константно-генериковое ядро:
//!   параметры поля — константы типа (проверяются компилятором),
//!   операции — `const fn`;
//! - [`GfRuntime`] — рантайм-слой: p, m и модуль задаются во время
//!   выполнения через [`FieldParams`] (модуль можно найти поиском:
//!   [`FieldParams::find`]).
//!
//! Плюс трейт [`FiniteField`] — универсальный контракт для
//! generic-алгоритмов, реализованный для обоих слоёв, с наборами
//! общих функций ([`poly_eval`], [`sqrt`]).
//!
//! Инварианты крейта: `no_std` (только `core`), `forbid(unsafe_code)`,
//! без аллокаций, MSRV 1.81, арифметика не паникует.
//! Соглашения нуля: `inv(0) = 0`, `x / 0 = 0`, `0^0 = 1`.
//!
//! # Представление
//!
//! Элемент GF(p^m) — многочлен над GF(p) степени `< m`,
//! коэффициенты по возрастанию; «упакованное» целое представление —
//! `Σ c_i·p^i` (базис-p цифры). Модуль поля — мономиальный
//! многочлен степени m, упакованный тем же способом без старшей
//! единицы: `POLY = Σ q_j·p^j` соответствует
//! `x^m + q_{m−1}·x^{m−1} + … + q_0`. Для p = 2 упаковка
//! совпадает с битовой из `gf2m` — одинаковые модули дают
//! одинаковую арифметику (см. тесты cross_check).
//!
//! # Пример
//! ```rust
//! use gfpm::{FieldParams, Gf9, GfRuntime};
//!
//! // GF(9) = GF(3)[x]/(x^2 + x + 2): 5 = x + 2, 3 = x
//! let a = Gf9::new(5);
//! let b = Gf9::new(3);
//! assert_eq!(a * b, Gf9::new(4)); // (x+2)·x = x + 1
//!
//! // Рантайм-слой: GF(125) с автоматически найденным модулем x^3 + x + 1
//! let params = FieldParams::find(5, 3).unwrap();
//! let a = GfRuntime::new(params, 7).unwrap(); // x + 2
//! let b = GfRuntime::new(params, 5).unwrap(); // x
//! assert_eq!(a * b, GfRuntime::new(params, 35).unwrap()); // x^2 + 2x
//! ```
//!
//! [`gf2m`]: https://docs.rs/gf2m

